// The same recovery manifest is used for imports and explicit removal. Hash is
// the bytes written by this operation (empty means removal), never a filename heuristic.
type backupEntry struct {
	Path    string `json:"path"`
	Backup  string `json:"backup"`
	Existed bool   `json:"existed"`
	Hash    string `json:"hash,omitempty"`
}

func (c *Connection) backupChanges(changes []cleanupChange) (string, map[string][]byte, error) {
	backup := filepath.Join(c.Dir, "connection-backups", backupName())
	if err := os.MkdirAll(backup, 0700); err != nil {
		return "", nil, err
	}
	originals := map[string][]byte{}
	manifest := []backupEntry{}
	for i, change := range changes {
		name := fmt.Sprintf("%d.bak", i+1)
		data, err := fsx.ReadBounded(change.path, 8*1024*1024)
		if err != nil && !os.IsNotExist(err) {
			return "", nil, err
		}
		if err == nil {
			originals[change.path] = data
			if err = os.WriteFile(filepath.Join(backup, name), data, 0600); err != nil {
				return "", nil, err
			}
		}
		hash := ""
		if change.data != nil {
			hash = fsx.Hash(change.data)
		}
		manifest = append(manifest, backupEntry{change.path, name, err == nil, hash})
	}
	raw, err := json.Marshal(map[string]any{"files": manifest})
	if err == nil {
		err = fsx.AtomicWrite(filepath.Join(backup, "manifest.json"), raw)
	}
	return backup, originals, err
}

type cleanupChange struct {
	path, hash string
	data       []byte
}

func named(m map[string]any, key, name string) any {
	items, _ := m[key].([]any)
	for _, item := range items {
		if entry, ok := item.(map[string]any); ok && entry["name"] == name {
			return entry
		}
	}
	return nil
}

func removeNamed(m map[string]any, key, name string, expected any) error {
	items, _ := m[key].([]any)
	kept := []any{}
	for _, item := range items {
		if entry, ok := item.(map[string]any); ok && entry["name"] == name {
			matches := reflect.DeepEqual(entry, expected)
			if name == "INTERNET" && !matches {
				// ExportPatch's subscription-independent form is also generated by us.
				if group, ok := expected.(map[string]any); ok {
					patch := map[string]any{}
					for key, value := range group {
						patch[key] = value
					}
					patch["proxies"] = []any{"DIRECT"}
					patch["include-all-proxies"], patch["include-all-providers"] = true, true
					delete(patch, "include-all")
					delete(patch, "use")
					matches = reflect.DeepEqual(entry, patch)
				}
			}
			if expected == nil || !matches {
				return fmt.Errorf("%s 已被修改，无法确认归属，未移除", name)
			}
		} else {
			kept = append(kept, item)
		}
	}
	if len(kept) != len(items) {
		m[key] = kept
	}
	return nil
}

func removeCampusParts(m, expected map[string]any, extension string) error {
	for key, name := range map[string]string{"proxies": "FDU-ROUTER", "proxy-groups": "INTERNET", "listeners": "FDU-FALLBACK"} {
		keys := []string{key}
		if extension == "proxies" && key == "proxies" || extension == "groups" && key == "proxy-groups" {
			keys = []string{"prepend", "append"}
		} else if extension != "" && extension != "merge" {
			continue
		}
		for _, field := range keys {
			if err := removeNamed(m, field, name, named(expected, key, name)); err != nil {
				return err
			}
		}
	}
	if providers, ok := m["rule-providers"].(map[string]any); ok {
		if provider, exists := providers["FDU-CAMPUS"]; exists {
			want, _ := expected["rule-providers"].(map[string]any)
			if !reflect.DeepEqual(provider, want["FDU-CAMPUS"]) {
				return errors.New("FDU-CAMPUS 规则接口已被修改，未移除")
			}
			delete(providers, "FDU-CAMPUS")
		}
	}
	for _, key := range []string{"rules", "prepend", "append"} {
		items, _ := m[key].([]any)
		kept := []any{}
		for _, item := range items {
			if item != "RULE-SET,FDU-CAMPUS,FDU-ROUTER" {
				kept = append(kept, item)
			}
		}
		if len(items) != len(kept) {
			m[key] = kept
		}
	}
	return nil
}

func emptyExtension(m map[string]any) bool {
	for key, value := range m {
		switch key {
		case "prepend", "append", "delete", "listeners":
			items, ok := value.([]any)
			if !ok || len(items) != 0 {
				return false
			}
		case "rule-providers":
			items, ok := value.(map[string]any)
			if !ok || len(items) != 0 {
				return false
			}
		default:
			return false
		}
	}
	return true
}

// RemoveCampus removes only the recorded integration of the currently selected
// client. Old current-format journals are supported by checking their generated
// entries against the existing planner, plus the journal's feed/profile hashes.
func (c *Connection) RemoveCampus(a CampusAttachment, values map[string]any) (string, error) {
	if _, err := campusProviderBytes(a); err != nil {
		return "", err
	}
	if match, err := campusProfile(a); err != nil || !match {
		if err == nil {
			err = ErrClashChanging
		}
		return "", err
	}
	if c.RuntimePath() != a.RuntimeFile {
		return "", ErrClashChanging
	}
	p, err := c.PrepareCampus(a.Root, a.Config, values)
	if err != nil {
		return "", err
	}
	if p.ProfileUID != a.ProfileUID || p.ProviderPath != a.ProviderPath || p.MixedPort != a.MixedPort {
		return "", ErrClashChanging
	}
	api, err := c.campusAPI(a)
	if err != nil {
		return "", err
	}
	var live map[string]any
	var selections proxyResponse
	if err = api.Do("GET", "/configs", nil, &live); err != nil {
		return "", err
	}
	if err = api.Do("GET", "/proxies", nil, &selections); err != nil {
		return "", err
	}
	outside, err := campusOutside(selections.Proxies, text(live["mode"]), UnsafeSet(p))
	if err != nil {
		return "", err
	}
	var expected map[string]any
	if err = yaml.Unmarshal([]byte(p.Payload), &expected); err != nil {
		return "", err
	}
	changes := []cleanupChange{}
	inputs := map[string]string{}
	for path, hash := range p.Inputs {
		inputs[path] = hash
	}
	readFile := func(path string) ([]byte, error) {
		// All writes are scoped to a selected client or the private GUI feed.
		for dir := path; ; dir = filepath.Dir(dir) {
			info, e := os.Lstat(dir)
			if e != nil {
				return nil, e
			}
			if info.Mode()&os.ModeSymlink != 0 {
				return nil, errors.New("不支持链接形式的配置路径")
			}
			if filepath.Dir(dir) == dir {
				break
			}
		}
		raw, e := fsx.ReadBounded(path, 8*1024*1024)
		if e != nil {
			return nil, e
		}
		inputs[path] = fsx.Hash(raw)
		return raw, nil
	}
	read := func(path string) (map[string]any, error) {
		raw, e := readFile(path)
		if e != nil {
			return nil, e
		}
		var m map[string]any
		e = yaml.Unmarshal(raw, &m)
		if e == nil && m == nil {
			e = errors.New("配置为空")
		}
		return m, e
	}
	queue := func(path string, m map[string]any, remove bool) error {
		var raw []byte
		var e error
		if !remove {
			raw, e = yaml.Marshal(m)
			if e != nil {
				return e
			}
		}
		if raw == nil || fsx.Hash(raw) != inputs[path] {
			changes = append(changes, cleanupChange{path, inputs[path], raw})
		}
		return nil
	}
	runtimePath := a.RuntimeFile
	if runtimePath == "" {
		runtimePath = filepath.Join(a.Root, "clash-verge.yaml")
	}
	runtime, err := read(runtimePath)
	if err != nil {
		return "", err
	}
	sourceInstalled := containsRuntimeFDU(runtime)
	for key, value := range runtimeOverrides(live, api) {
		runtime[key] = value
	}
	rollbackPayload := p.Payload
	if sourceInstalled || a.RuntimeFile == "" {
		raw, e := yaml.Marshal(runtime)
		if e != nil {
			return "", e
		}
		rollbackPayload = string(raw)
	}
	if err = removeCampusParts(runtime, expected, ""); err != nil {
		return "", err
	}
	for key, value := range runtimeOverrides(live, api) {
		runtime[key] = value
	}
	if a.RuntimeFile == "" {
		metaPath := filepath.Join(a.Root, "profiles.yaml")
		meta, e := read(metaPath)
		if e != nil {
			return "", e
		}
		items, _ := meta["items"].([]any)
		var active map[string]any
		for _, item := range items {
			if entry, ok := item.(map[string]any); ok && entry["uid"] == a.ProfileUID {
				active = entry
			}
		}
		if active == nil {
			return "", ErrClashChanging
		}
		options, _ := active["option"].(map[string]any)
		removed := map[string]bool{}
		for _, kind := range []string{"proxies", "groups", "merge", "rules", "script"} {
			uid, _ := options[kind].(string)
			if uid == "" {
				continue
			}
			var entry map[string]any
			for _, item := range items {
				if m, ok := item.(map[string]any); ok && m["uid"] == uid {
					entry = m
				}
			}
			file, _ := entry["file"].(string)
			if entry["type"] != kind || file == "" || filepath.Base(file) != file {
				return "", errors.New("订阅扩展归属不明确")
			}
			path := filepath.Join(a.Root, "profiles", file)
			shared := false
			for _, item := range items {
				other, ok := item.(map[string]any)
				if !ok || other["uid"] == a.ProfileUID {
					continue
				}
				option, _ := other["option"].(map[string]any)
				shared = shared || option[kind] == uid
			}
			if kind == "script" {
				raw, e := readFile(path)
				if e != nil {
					return "", e
				}
				script, _, e := renderExportPatch(p)
				if e != nil {
					return "", e
				}
				if strings.TrimSpace(string(raw)) != strings.TrimSpace(script) {
					if strings.Contains(string(raw), "FDU-ROUTER") || strings.Contains(string(raw), "FDU-CAMPUS") || strings.Contains(string(raw), "FDU Bridge") {
						return "", errors.New("FDU 脚本已被修改，无法确认归属，未移除")
					}
					continue
				}
				delete(options, kind)
				if !shared {
					removed[uid] = true
					if e = queue(path, nil, true); e != nil {
						return "", e
					}
				}
				continue
			}
			m, e := read(path)
			if e != nil {
				return "", e
			}
			if e = removeCampusParts(m, expected, kind); e != nil {
				return "", e
			}
			owned := entry["name"] == "FDU "+kind && entry["desc"] == "Managed by FDU node and rule manager" && strings.HasPrefix(uid, "fdu-") && file == uid+".yaml"
			remove := owned && !shared && emptyExtension(m)
			if remove {
				delete(options, kind)
				removed[uid] = true
			}
			if e = queue(path, m, remove); e != nil {
				return "", e
			}
		}
		kept := []any{}
		for _, item := range items {
			m, ok := item.(map[string]any)
			if !ok || !removed[text(m["uid"])] {
				kept = append(kept, item)
			}
		}
		meta["items"] = kept
		if err = queue(metaPath, meta, false); err != nil {
			return "", err
		}
	}
	payload, err := yaml.Marshal(runtime)
	if err != nil {
		return "", err
	}
	if strings.Contains(string(payload), "FDU-ROUTER") || strings.Contains(string(payload), "FDU-CAMPUS") || strings.Contains(string(payload), "FDU-FALLBACK") {
		return "", errors.New("用户配置仍引用 FDU 项目，请先解除引用")
	}
	// Runtime-overlay clients retain their original source file byte for byte.
	if a.RuntimeFile == "" || sourceInstalled {
		if err = queue(runtimePath, runtime, false); err != nil {
			return "", err
		}
	}
	if _, err = read(a.ProviderPath); err != nil {
		return "", err
	}
	if inputs[a.ProviderPath] != a.ProviderHash {
		return "", ErrClashChanging
	}
	changes = append(changes, cleanupChange{a.ProviderPath, a.ProviderHash, nil})
	backup, originals, err := c.backupChanges(changes)
	if err != nil {
		return "", err
	}
	check := func() error {
		for path, hash := range inputs {
			if fsx.HashFile(path) != hash {
				return ErrClashChanging
			}
		}
		return nil
	}
	if err = check(); err != nil {
		return "", err
	}
	var current map[string]any
	if err = api.Do("GET", "/configs", nil, &current); err != nil {
		return "", err
	}
	if !reflect.DeepEqual(runtimeOverrides(live, api), runtimeOverrides(current, api)) {
		return "", ErrClashChanging
	}
	var written []cleanupChange
	reloadAttempted := false
	for _, change := range changes {
		if fsx.HashFile(change.path) != change.hash {
			err = ErrClashChanging
			break
		}
		if change.data == nil {
			err = os.Remove(change.path)
		} else {
			err = fsx.AtomicWrite(change.path, change.data)
		}
		if err != nil {
			break
		}
		written = append(written, change)
	}
	if err == nil {
		reloadAttempted = true
		err = api.Do("PUT", "/configs?force=true", map[string]string{"payload": string(payload)}, nil)
	}
	if err == nil {
		var after proxyResponse
		err = api.Do("GET", "/proxies", nil, &after)
		if err == nil && (after.Proxies["FDU-ROUTER"] != nil || after.Proxies["INTERNET"] != nil) {
			err = errors.New("Clash 未确认移除 FDU 配置")
		}
		if err == nil {
			err = restoreCleanupSelections(api, selections.Proxies, outside, true)
		}
		if err == nil {
			var config map[string]any
			if err = api.Do("GET", "/configs", nil, &config); err == nil && (!reflect.DeepEqual(live["tun"], config["tun"]) || live["mode"] != config["mode"]) {
				err = errors.New("Clash 模式或 TUN 状态已变化")
			}
		}
		if err == nil {
			return backup, nil
		}
	}
	// Keep both the import journal and this backup on every failure.
	var failures []string
	for _, change := range slices.Backward(written) {
		want := ""
		if change.data != nil {
			want = fsx.Hash(change.data)
		}
		if fsx.HashFile(change.path) != want {
			failures = append(failures, filepath.Base(change.path)+" 已变化，未恢复")
			continue
		}
		if old, ok := originals[change.path]; ok {
			if e := fsx.AtomicWrite(change.path, old); e != nil {
				failures = append(failures, e.Error())
			}
		}
	}
	if reloadAttempted && len(failures) == 0 && check() == nil {
		if e := api.Do("PUT", "/configs?force=true", map[string]string{"payload": rollbackPayload}, nil); e != nil {
			failures = append(failures, "Clash 恢复未确认："+e.Error())
		} else if e = restoreCleanupSelections(api, selections.Proxies, "", false); e != nil {
			failures = append(failures, e.Error())
		}
	}
	return "", fmt.Errorf("移除未完成：%w；已保留恢复记录和备份 %s\n%s", err, backup, strings.Join(failures, "\n"))
}

// Reloads may reset user selectors. Restore all of them, and verify the result.
// Only a successful removal substitutes the Internet exit for deleted FDU nodes.
func restoreCleanupSelections(api API, saved Proxies, outside string, removed bool) error {
	var response proxyResponse
	if err := api.Do("GET", "/proxies", nil, &response); err != nil {
		return err
	}
	wanted := map[string]string{}
	for name, previous := range saved {
		if previous.Type != "Selector" || removed && name == "INTERNET" {
			continue
		}
		target := previous.Now
		if removed && (target == "FDU-ROUTER" || target == "INTERNET") {
			target = outside
		}
		current := response.Proxies[name]
		if current == nil || current.Type != "Selector" || !contains(current.All, target) || response.Proxies[target] == nil {
			return fmt.Errorf("无法保留 %s 的选择", name)
		}
		wanted[name] = target
		if current.Now != target {
			if err := api.Do("PUT", "/proxies/"+url.PathEscape(name), map[string]string{"name": target}, nil); err != nil {
				return err
			}
		}
	}
	if err := api.Do("GET", "/proxies", nil, &response); err != nil {
		return err
	}
	for name, target := range wanted {
		if response.Proxies[name] == nil || response.Proxies[name].Now != target {
			return fmt.Errorf("Clash 未确认保留 %s 的选择", name)
		}
	}
	return nil
}
